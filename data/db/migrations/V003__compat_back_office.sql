-- Compatibilité avec le back-office Directus :
--   * les listes (alias, modes, périodes…) passent de text[] à jsonb : Directus édite les tableaux JSON avec son
--     interface « étiquettes », pas les tableaux natifs PostgreSQL ;
--   * les identifiants techniques « uid » acceptent une valeur fournie (restauration, import) : BY DEFAULT.

DROP TRIGGER place_search ON place;

ALTER TABLE mode            ALTER COLUMN schedule_kinds DROP DEFAULT,
                            ALTER COLUMN schedule_kinds TYPE jsonb USING to_jsonb(schedule_kinds),
                            ALTER COLUMN schedule_kinds SET DEFAULT '[]';
ALTER TABLE place           ALTER COLUMN aliases DROP DEFAULT,
                            ALTER COLUMN aliases TYPE jsonb USING to_jsonb(aliases),
                            ALTER COLUMN aliases SET DEFAULT '[]';
ALTER TABLE hub             ALTER COLUMN aliases DROP DEFAULT,
                            ALTER COLUMN aliases TYPE jsonb USING to_jsonb(aliases),
                            ALTER COLUMN aliases SET DEFAULT '[]';
ALTER TABLE fare            ALTER COLUMN categories DROP DEFAULT,
                            ALTER COLUMN categories TYPE jsonb USING to_jsonb(categories),
                            ALTER COLUMN categories SET DEFAULT '[]';
ALTER TABLE coverage        ALTER COLUMN modes DROP DEFAULT,
                            ALTER COLUMN modes TYPE jsonb USING to_jsonb(modes),
                            ALTER COLUMN modes SET DEFAULT '[]';
ALTER TABLE time_band_group ALTER COLUMN periods TYPE jsonb USING to_jsonb(periods),
                            ALTER COLUMN day_types TYPE jsonb USING to_jsonb(day_types);

ALTER TABLE mode     ADD CONSTRAINT mode_schedule_kinds_array CHECK (jsonb_typeof(schedule_kinds) = 'array');
ALTER TABLE place    ADD CONSTRAINT place_aliases_array CHECK (jsonb_typeof(aliases) = 'array');
ALTER TABLE hub      ADD CONSTRAINT hub_aliases_array CHECK (jsonb_typeof(aliases) = 'array');
ALTER TABLE fare     ADD CONSTRAINT fare_categories_array CHECK (jsonb_typeof(categories) = 'array');
ALTER TABLE coverage ADD CONSTRAINT coverage_modes_array CHECK (jsonb_typeof(modes) = 'array');

CREATE OR REPLACE FUNCTION place_search_refresh() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    NEW.search := thniya_norm(concat_ws(' ', NEW.id, NEW.name_fr, NEW.name_ar, NEW.area_fr,
        (SELECT string_agg(a, ' ') FROM jsonb_array_elements_text(coalesce(NEW.aliases, '[]')) AS a)));
    RETURN NEW;
END $$;
CREATE TRIGGER place_search BEFORE INSERT OR UPDATE ON place FOR EACH ROW EXECUTE FUNCTION place_search_refresh();
UPDATE place SET id = id;

DO $$
DECLARE r record;
BEGIN
    FOR r IN SELECT table_name FROM information_schema.columns
             WHERE table_schema = 'public' AND column_name = 'uid' AND is_identity = 'YES'
    LOOP
        EXECUTE format('ALTER TABLE %I ALTER COLUMN uid SET GENERATED BY DEFAULT', r.table_name);
    END LOOP;
END $$;
